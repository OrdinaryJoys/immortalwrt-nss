def render(driver, clients):
    trees = {"driver": driver, "clients": clients}
    bodies, provenance = {}, {}
    for group, (label, relative, names) in GROUPS.items():
        raw = (trees[label] / relative).read_text()
        bodies[group] = {}
        for name in names:
            body = extract.function(raw, name)
            bodies[group][name] = body
            provenance[name] = {"path": relative, "line": raw[:raw.index(body)].count("\n")+1,
                                "sha256": sha(body.encode()), "coverage": "COMPLETE_ACTUAL_BODY"}
    dynamic = (driver / "exports/nss_dynamic_interface.h").read_text()
    public = (driver / "exports/nss_api_if.h").read_text()
    tunip = (clients / "exports/nss_connmgr_tunipip6.h").read_text()
    mirror = (clients / "mirror/nss_mirror_ctl.c").read_text()
    tunip_c = (clients / "tunipip6/nss_connmgr_tunipip6_sysctl.c").read_text()
    constants = []
    names = ["NSS_MAX_DYNAMIC_INTERFACES", "NSS_MAX_PHYSICAL_INTERFACES", "NSS_MAX_VIRTUAL_INTERFACES",
             "NSS_MAX_TUNNEL_INTERFACES", "NSS_PHYSICAL_IF_START", "NSS_VIRTUAL_IF_START", "NSS_TUNNEL_IF_START",
             "NSS_DYNAMIC_IF_START", "NSS_SPECIAL_IF_START", "NSS_N2H_INTERFACE", "NSS_ETH_RX_INTERFACE"]
    for name in names:
        constants.append(one(r"^#define " + name + r"[^\n]*", dynamic + "\n" + public))
    for text, selected in ((mirror, ["NSS_MIRROR_CONFIG_PARAM_NUM", "NSS_MIRROR_SET_NEXTHOP_PARAM_NUM", "NSS_MIRROR_ENABLE_INGRESS_PMC_NUM"]),
                           (tunip_c, ["MAX_PROC_SIZE", "MAX_DATA_LEN", "MAX_IPV4_PREFIX_LEN", "MAX_IPV6_PREFIX_LEN", "MAX_PSID_OFFSET_LEN", "NETDEV_STR_LEN", "PREFIX_STR_LEN"]),
                           ((driver / "nss_ppe_vp.h").read_text(), ["NSS_PPE_VP_MAX_CMD_STR"])):
        for name in selected:
            constants.append(one(r"^#define " + name + r"[^\n]*", text))
    types = [*constants, enum(dynamic, "nss_dynamic_interface_type"),
             one(r"typedef enum\s*\{\s*NSS_TX_SUCCESS[^{}]*\}\s*nss_tx_status_t;", (driver / "exports/nss_cmn.h").read_text()),
             enum((driver / "exports/nss_mirror.h").read_text(), "nss_mirror_pkt_clone_point"),
             enum(mirror, "nss_mirror_ctl_cmd_type"), enum(tunip_c, "nss_tunipip6_sysctl_mode"),
             enum(tunip, "nss_connmgr_tunipip6_err_codes"), enum(tunip, "nss_connmgr_tunipip6_maprule_type"),
             one(r"struct nss_connmgr_tunipip6_maprule_cfg\s*\{[^{}]*\};", tunip)]
    return bodies, "\n\n".join(types)+"\n", provenance


def check_profile(driver, clients):
    profile_path = REPO / "tests/nss-command-inputs/profile.json"
    profile = json.loads(profile_path.read_text())
    if profile["schema"] != 1:
        raise ValueError("PROFILE_SCHEMA")
    for name,digest in profile["metadata_rule_inputs"].items():
        if sha((REPO/name).read_bytes()) != digest:
            raise ValueError("FIXED_PREPARE_METADATA_RULES")
    for label, tree in (("driver", driver), ("clients", clients)):
        code, metadata = partition(tree)
        if (len(code)!=profile[label]["files"] or
                inventory_hash(code) != profile[label]["candidate_inventory_sha256"]):
            raise ValueError("FIXED_CANDIDATE_TREE: " + label)
        package = REPO / "package/qca-nss" / profile[label]["package"]
        patches = {p.name: sha(p.read_bytes()) for p in sorted((package / "patches").glob("*.patch"))}
        if patches != profile[label]["patches"]:
            raise ValueError("FIXED_PATCH_INPUTS: " + label)
        recipe = (package / "Makefile").read_text()
        if not profile[label]["pin"].startswith(one(r"^PKG_SOURCE_VERSION:=(\S+)$", recipe)):
            raise ValueError("FIXED_VENDOR_PIN")
        release=one(r"^PKG_RELEASE:=(\S+)$",recipe)
        normalized=re.sub(r"^PKG_RELEASE:=\S+$","PKG_RELEASE:=REVIEWED_RELEASE_ONLY",recipe,flags=re.M)
        if release not in profile[label]["allowed_releases"] or sha(normalized.encode()) != profile[label]["recipe_without_release_sha256"]:
            raise ValueError("FIXED_RECIPE_EXCEPT_KNOWN_RELEASE")
    return profile
