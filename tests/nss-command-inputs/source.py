def sha(data):
    return hashlib.sha256(data).hexdigest()


def inventory(root):
    result = {}
    for p in sorted(root.rglob("*")):
        if p.is_symlink():
            raise ValueError("SYMLINK_INPUT")
        if p.is_file():
            result[p.relative_to(root).as_posix()] = sha(p.read_bytes())
    return result


def inventory_hash(items):
    return sha(json.dumps(items,sort_keys=True,separators=(",", ":")).encode())


def partition(root):
    """Only metadata generated by package-defaults.mk/package.mk is excepted."""
    code, metadata = {}, {}
    for p in sorted(root.rglob("*")):
        if p.is_symlink():
            raise ValueError("SYMLINK_INPUT")
        if not p.is_file():
            continue
        name=p.relative_to(root).as_posix()
        raw=p.read_bytes()
        if name=="version.date":
            if not re.fullmatch(rb"[0-9]{1,19}\n",raw):
                raise ValueError("VERSION_DATE_CONTENT")
            metadata[name]=sha(raw)
        elif re.fullmatch(r"\.prepared_[0-9a-f]{32}_[0-9a-f]{32}",name):
            if raw or any(k.startswith(".prepared_") for k in metadata):
                raise ValueError("PREPARED_STAMP_CONTENT_OR_DUPLICATE")
            metadata[name]=sha(raw)
        else:
            code[name]=sha(raw)
    return code, metadata


def one(pattern, text):
    matches = re.findall(pattern, text, re.S | re.M)
    if len(matches) != 1:
        raise ValueError("DECLARATION: " + pattern)
    return matches[0]


def enum(text, name):
    return one(r"(?:typedef )?enum " + name + r"\s*\{[^{}]*\}[^;]*;", text)


